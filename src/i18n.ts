const dictionaries: Record<Lang, Record<Key, string>> = { ru, en };

export function translate(lang: Lang, key: Key, ...args: (string | number)[]): string {
  let s = dictionaries[lang][key] ?? key;
  args.forEach((a, i) => (s = s.replaceAll(`{${i}}`, String(a))));
  return s;
}

/** "1 page", "3 pages"; for Russian the form after «на»: "1 странице", "3 страницах". */
export function countPages(lang: Lang, n: number): string {
  if (lang === 'en') return `${n} ${n === 1 ? 'page' : 'pages'}`;
  return `${n} ${n % 10 === 1 && n % 100 !== 11 ? 'странице' : 'страницах'}`;
}

/** "1 word", "312 words"; "1 слово", "2 слова", "5 слов". */
export function countWords(lang: Lang, n: number): string {
  const num = n.toLocaleString(lang === 'ru' ? 'ru-RU' : 'en-US');
  if (lang === 'en') return `${num} ${n === 1 ? 'word' : 'words'}`;
  const d10 = n % 10;
  const d100 = n % 100;
  const form = d10 === 1 && d100 !== 11 ? 'слово' : d10 >= 2 && d10 <= 4 && (d100 < 12 || d100 > 14) ? 'слова' : 'слов';
  return `${num} ${form}`;
}

export function detectLang(): Lang {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem('exomyth:lang');
  } catch {
    /* Storage can be blocked (private mode, sandboxed frames); fall back to the browser language. */
  }
  if (saved === 'ru' || saved === 'en') return saved;
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}
